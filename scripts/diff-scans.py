#!/usr/bin/env python3
"""Dev-only helper: compare the baseline scans of nginx:1.25-bookworm with the rescan of our image.

Reads baseline/baseline-*.json and rescan/rescan-*.json (the JSON reports are regenerated by the scan
commands in LOG.md / scripts/filter-baseline.sh and are not committed) and prints Markdown.
A finding is identified by (CVE id, package name); versions are ignored on purpose, so a package that
moved to a fixed version shows up as "gone".   Usage: diff-scans.py [> rescan/diff.md]
"""
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = ["critical", "high", "medium", "low", "negligible", "unknown"]


def load(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def trivy(path):
    out = {}
    for r in load(path).get("Results", []):
        for v in r.get("Vulnerabilities") or []:
            out[(v["VulnerabilityID"], v["PkgName"])] = (v["Severity"].lower(), v.get("FixedVersion") or "")
    return out


def grype(path):
    out = {}
    for m in load(path)["matches"]:
        v, a = m["vulnerability"], m["artifact"]
        fixed = ",".join(v.get("fix", {}).get("versions", []))
        out[(v["id"], a["name"])] = (v["severity"].lower(), fixed)
    return out


def sev_line(findings):
    c = Counter(s for s, _ in findings.values())
    return ", ".join(f"{k} {c[k]}" for k in ORDER if c[k]) or "none"


SETS = [
    ("Trivy (default)", trivy, "baseline/baseline-trivy.json", "rescan/rescan-trivy.json"),
    ("Grype (default, Debian tracker)", grype, "baseline/baseline-grype.json", "rescan/rescan-grype.json"),
    ("Grype (CPE matching on, sees nginx's own CVEs)", grype, "baseline/baseline-grype-cpe.json",
     "rescan/rescan-grype-cpe.json"),
]

print("# Baseline vs rescan\n")
print("Baseline = `nginx:1.25-bookworm`; rescan = our image `echo-nginx:test`. Same scanner versions and settings.\n")
results = {}
for name, fn, b_path, a_path in SETS:
    before, after = fn(b_path), fn(a_path)
    results[name] = (before, after)
    gone, added, kept = set(before) - set(after), set(after) - set(before), set(before) & set(after)
    print(f"## {name}\n")
    print("| | Findings | By severity |\n|---|---|---|")
    print(f"| Baseline | {len(before)} | {sev_line(before)} |")
    print(f"| Rescan | {len(after)} | {sev_line(after)} |")
    print(f"\nGone: **{len(gone)}**, still present: {len(kept)}, **new in rescan: {len(added)}**.\n")
    drop = Counter(p for _, p in gone)
    print("Packages that lost the most findings: " + ", ".join(f"{p} ({n})" for p, n in drop.most_common(8)) + "\n")
    if added:
        print("New in the rescan (package: count): " +
              ", ".join(f"{p} ({n})" for p, n in Counter(p for _, p in added).most_common(8)) + "\n")

# --- the CVEs this assignment targets -------------------------------------------------------------------
tb, ta = results[SETS[0][0]]
gb, ga = results[SETS[2][0]]
LIBSSL = ["CVE-2026-31789", "CVE-2024-6119", "CVE-2025-15467", "CVE-2025-69421", "CVE-2026-28387",
          "CVE-2026-28388", "CVE-2026-28389", "CVE-2026-28390", "CVE-2026-45447", "CVE-2026-84782"]
print("## The OpenSSL bump (libssl3), per CVE, Trivy\n")
print("| CVE | Baseline | Rescan |\n|---|---|---|")
for cve in LIBSSL:
    b, a = tb.get((cve, "libssl3")), ta.get((cve, "libssl3"))
    print(f"| {cve} | {b[0] + ', fixed in ' + b[1] if b else 'absent'} | {'STILL PRESENT' if a else 'gone'} |")
print("\nlibssl3 findings left in the rescan: " +
      (", ".join(f"{c} ({s})" for (c, p), (s, _) in sorted(ta.items()) if p == "libssl3") or "none") + "\n")

print("## nginx's own CVEs (Grype with CPE matching)\n")
nb = {k for k in gb if k[1] == "nginx"}
na = {k for k in ga if k[1] == "nginx"}
print(f"nginx findings: baseline {len(nb)}, rescan {len(na)} (the version string is unchanged, so scanners "
      f"keep flagging every nginx CVE, including the one we patched).\n")
t = ("CVE-2024-7347", "nginx")
print(f"CVE-2024-7347 (our backport): baseline {'flagged' if t in gb else 'absent'}, "
      f"rescan {'**still flagged**' if t in ga else 'gone'} -> needs the VEX document.\n")

# --- anything that got worse ------------------------------------------------------------------------------
print("## Anything new or worse?\n")
for name, (before, after) in results.items():
    worse = [(k, before[k][0], after[k][0]) for k in set(before) & set(after)
             if ORDER.index(after[k][0]) < ORDER.index(before[k][0])]
    print(f"- {name}: {len(set(after) - set(before))} new findings, {len(worse)} with a higher severity.")

# --- why did findings disappear? Attribute each one using the package lists (SBOMs) ------------------------
def packages(path):
    return {a["name"]: a["version"] for a in load(path)["artifacts"] if a.get("type") == "deb"}


pb, pa = packages("baseline/baseline-sbom-syft.json"), packages("rescan/rescan-sbom-syft.json")
removed = sorted(set(pb) - set(pa))
added = sorted(set(pa) - set(pb))
upgraded = sorted(p for p in set(pb) & set(pa) if pb[p] != pa[p])
same = [p for p in set(pb) & set(pa) if pb[p] == pa[p]]
print("\n## Why findings disappeared (Trivy default, attributed with the package lists)\n")
print(f"Image content (deb packages): baseline {len(pb)}, rescan {len(pa)}; removed {len(removed)}, "
      f"added {len(added)}, version changed {len(upgraded)}, unchanged {len(same)}.\n")
gone = set(tb) - set(ta)
cause = Counter()
for _, pkg in gone:
    cause["package removed from the image" if pkg not in pa else
          "package still installed, version changed" if pb.get(pkg) != pa.get(pkg) else
          "package unchanged (scanner data changed)"] += 1
print("| Cause | Findings gone |\n|---|---|")
for k, n in cause.most_common():
    print(f"| {k} | {n} |")
print(f"\nRemoved packages with findings (top): " + ", ".join(
    f"{p} ({n})" for p, n in Counter(p for _, p in gone if p not in pa).most_common(10)) + "\n")
print("Targeted libraries (installed version before -> after): " + ", ".join(
    f"{p} {pb.get(p, '-')} -> {pa.get(p, '-')}" for p in ("libssl3", "libpcre2-8-0", "zlib1g", "libc6")) + "\n")
print("Debian base: baseline reports Debian " + str(load("baseline/baseline-trivy.json")["Metadata"]["OS"]["Name"])
      + ", rescan Debian " + str(load("rescan/rescan-trivy.json")["Metadata"]["OS"]["Name"])
      + " (a newer point release alone fixes many library CVEs, so the totals above are not all our work).\n")

print("## Scanner database dates (the two scans ran about a day apart)\n")
for name, path in (("Grype baseline", "baseline/baseline-grype.json"), ("Grype rescan", "rescan/rescan-grype.json")):
    print(f"- {name}: database built {load(path)['descriptor']['db']['status']['built']}")
print("- Trivy: the database is fetched fresh on each run; its date is not recorded in the report.\n"
      "- Effect: a CVE published in between can appear as 'new' (e.g. CVE-2026-107494 on libssl3 in Grype; "
      "re-scanning upstream with the newer database flags it there too).")
